import {mkdir,cp,readFile,writeFile,realpath} from 'node:fs/promises';
import {randomBytes} from 'node:crypto';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const skill=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const repo=await realpath(path.resolve(skill,'../..'));
const [destination,origin]=process.argv.slice(2);
if(!destination||!origin)throw new Error('Usage: node create-instance.mjs /new/absolute/private-directory https://your-host');
const url=new URL(origin);
if(url.protocol!=='https:'||url.origin!==origin||url.username||url.password||!/^[A-Za-z0-9.:-]+$/.test(url.host))throw new Error('Provide an exact HTTPS origin, without path or credentials');
if(!path.isAbsolute(destination))throw new Error('Destination must be absolute');
const dest=path.join(await realpath(path.dirname(destination)),path.basename(destination));
if(dest===repo||dest.startsWith(repo+path.sep))throw new Error('Private instances must be outside the public repository');
await mkdir(dest,{mode:0o700}); // Existing destination is rejected, not merged.
const backend=path.join(dest,'backend');
await cp(path.join(skill,'assets/backend'),backend,{recursive:true});
await mkdir(path.join(backend,'data'),{mode:0o700});
const secrets={ADMIN_TOKEN:randomBytes(32).toString('hex'),DEVICE_TOKEN:randomBytes(32).toString('hex')};
await writeFile(path.join(backend,'secrets.json'),JSON.stringify(secrets),{mode:0o600,flag:'wx'});
await writeFile(path.join(backend,'.env'),`APP_ORIGIN=${origin}\nSITE_HOST=${url.host}\n`,{mode:0o600,flag:'wx'});
const device=path.join(dest,'device-stage/kindle-note');
const documents=path.join(dest,'device-stage/documents');
await mkdir(device,{recursive:true,mode:0o700});await mkdir(documents,{recursive:true,mode:0o700});
for(const name of ['kindle-note-worker-v6.sh','manual-power-v6.sh','ui-start-gate.sh'])await cp(path.join(skill,'assets/device',name),path.join(device,name));
await cp(path.join(skill,'assets/device/touch-actions.sh'),path.join(device,'touch-actions-v6.sh'));
await cp(path.join(skill,'assets/device/Kindle-Note-Start-V6.sh'),path.join(documents,'Kindle-Note-Start-V6.sh'));
await writeFile(path.join(device,'base-url'),origin+'\n',{mode:0o600});
await writeFile(path.join(device,'device-curl.conf'),`header = "Authorization: Bearer ${secrets.DEVICE_TOKEN}"\n`,{mode:0o600});
await writeFile(path.join(dest,'private-access.txt'),`${origin}/#key=${secrets.ADMIN_TOKEN}\nKeep this link private.\n`,{mode:0o600,flag:'wx'});
console.log('Created independent private instance. No server started and no USB files changed. Read deployment/device instructions next.');
